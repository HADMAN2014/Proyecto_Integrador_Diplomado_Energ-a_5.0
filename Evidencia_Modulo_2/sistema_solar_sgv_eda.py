# 5. ENTRENAMIENTO DE RED NEURONAL RECURRENTE (RNN) Y PRONÓSTICO DE TIEMPO EQUIVALENTE (40 MESES HASTA 2030)
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, SimpleRNN

# Agrupar datos por mes y año para tener una serie de tiempo consistente
df_monthly = df.set_index('Timestamp').resample('ME')['P_DC_PV_W'].mean().reset_index()
series_data = df_monthly['P_DC_PV_W'].values.reshape(-1, 1)

# Determinar la longitud equivalente del dataset en meses
n_meses_equivalentes = len(df_monthly)
print(f"El dataset contiene {n_meses_equivalentes} meses de datos históricos.")

# Escalar los datos para optimizar el entrenamiento de la RNN
scaler_rnn = MinMaxScaler(feature_range=(0, 1))
scaled_series = scaler_rnn.fit_transform(series_data)

# Crear estructura de datos temporal con ventana (lookback = 3 meses)
def create_dataset(dataset, look_back=3):
    X_data, y_data = [], []
    for i in range(len(dataset) - look_back):
        X_data.append(dataset[i:(i + look_back), 0])
        y_data.append(dataset[i + look_back, 0])
    return np.array(X_data), np.array(y_data)

look_back = 3
X_rnn, y_rnn = create_dataset(scaled_series, look_back)

# Formatear la entrada para la RNN: [muestras, pasos_de_tiempo, caracteristicas]
X_rnn = np.reshape(X_rnn, (X_rnn.shape[0], X_rnn.shape[1], 1))

# Construir un modelo RNN Simple secuencial
model_rnn = Sequential([
    SimpleRNN(16, activation='tanh', input_shape=(look_back, 1)),
    Dense(1)
])
model_rnn.compile(optimizer='adam', loss='mse')
model_rnn.fit(X_rnn, y_rnn, epochs=120, batch_size=2, verbose=0)

# Pronosticar secuencialmente un tiempo equivalente (40 meses a futuro)
last_window = list(scaled_series[-look_back:].flatten())
predictions_scaled = []

# Pronosticar autoregresivamente paso a paso
for _ in range(n_meses_equivalentes):
    input_seq = np.array(last_window[-look_back:]).reshape(1, look_back, 1)
    pred = model_rnn.predict(input_seq, verbose=0)[0][0]
    predictions_scaled.append(pred)
    last_window.append(pred)

# Transformar las predicciones inversamente a la escala original
predictions_original = scaler_rnn.inverse_transform(np.array(predictions_scaled).reshape(-1, 1)).flatten()

# Crear las fechas mensuales correspondientes al horizonte de tiempo equivalente
last_date = df_monthly['Timestamp'].iloc[-1]
forecast_dates = pd.date_range(start=last_date + pd.offsets.MonthEnd(1), periods=n_meses_equivalentes, freq='ME')

df_forecast_equiv = pd.DataFrame({
    'Timestamp': forecast_dates,
    'P_DC_PV_W_Pred': predictions_original
})

# --- GRAFICAR EL PRONÓSTICO HISTÓRICO + TIEMPO EQUIVALENTE ---
plt.figure(figsize=(12, 5))
plt.plot(df_monthly['Timestamp'], df_monthly['P_DC_PV_W'], marker='o', label='Histórico Real (2023-2026)', color='darkorange')
plt.plot(df_forecast_equiv['Timestamp'], df_forecast_equiv['P_DC_PV_W_Pred'], marker='s', linestyle='--', label=f'Pronóstico RNN Equivalente ({n_meses_equivalentes} Meses a Futuro)', color='crimson')
plt.title('Pronóstico RNN de Generación de Energía (P_DC_PV_W) para Tiempo Equivalente (Hasta 2030)')
plt.xlabel('Fecha')
plt.ylabel('Generación Promedio (W)')
plt.grid(True, linestyle='--', alpha=0.5)
plt.legend()
plt.tight_layout()
plt.savefig('dashboard_plots/rnn_forecast_equivalent.png')
plt.close()

print("Pronóstico de tiempo equivalente para la RNN completado y graficado exitosamente.")

