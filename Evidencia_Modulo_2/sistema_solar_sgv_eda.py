import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.neural_network import MLPClassifier
from sklearn.metrics import classification_report, confusion_matrix, roc_curve, auc, precision_recall_curve

# Usamos 'Grid_Status' como objetivo de clasificación ya que posee múltiples clases representativas
le = LabelEncoder()
df['Target_Class'] = le.fit_transform(df['Grid_Status'])
class_names = [str(c) for c in le.classes_]

features_cols = ['P_DC_PV_W', 'V_Batt_V', 'I_Batt_A', 'SoC_Batt_Pct', 'V_AC_L1_V', 'Temp_Inverter_C', 'Fault_Duration_Min']
X = df[features_cols]
y = df['Target_Class']

# División de datos estable
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42, stratify=y)

scaler_nn = StandardScaler()
X_train_scaled = scaler_nn.fit_transform(X_train)
X_test_scaled = scaler_nn.transform(X_test)

# Definir y entrenar la red neuronal (MLP Classifier)
mlp = MLPClassifier(hidden_layer_sizes=(64, 32), max_iter=300, random_state=42)
mlp.fit(X_train_scaled, y_train)

y_pred = mlp.predict(X_test_scaled)
y_prob = mlp.predict_proba(X_test_scaled)

